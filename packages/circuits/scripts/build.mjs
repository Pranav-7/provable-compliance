#!/usr/bin/env node
/**
 * Builds the eligibility circuit and its EVM verifier.
 *
 *   1. Compiles the Noir program to ACIR (target/eligibility.json).
 *   2. Derives the UltraHonk verification key (EVM target, zero-knowledge).
 *   3. Emits the matching Solidity verifier into the contracts package.
 *
 * Step 2 needs Aztec's public trusted-setup (CRS). bb.js downloads it once to
 * ~/.bb-crs and reuses it afterwards. Pass --skip-verifier to only compile.
 */
import { compile, createFileManager } from '@noir-lang/noir_wasm';
import { Barretenberg, UltraHonkBackend } from '@aztec/bb.js';
import { mkdir, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const circuitDir = join(root, 'eligibility');
const targetDir = join(root, 'target');
const verifierOut = join(root, '..', 'contracts', 'src', 'generated', 'HonkVerifier.sol');
const skipVerifier = process.argv.includes('--skip-verifier');

const quiet = (fn) => async (...args) => {
  const saved = { log: console.log, info: console.info, debug: console.debug };
  console.log = console.info = console.debug = () => {};
  try {
    return await fn(...args);
  } finally {
    Object.assign(console, saved);
  }
};

async function main() {
  const started = Date.now();
  const { program } = await quiet(compile)(createFileManager(circuitDir));
  await mkdir(targetDir, { recursive: true });
  await writeFile(join(targetDir, 'eligibility.json'), JSON.stringify(program));
  const digest = createHash('sha256').update(program.bytecode).digest('hex').slice(0, 16);
  console.log(`  circuit compiled          eligibility.json (acir ${digest})`);

  if (skipVerifier) return;

  const bb = await Barretenberg.new();
  try {
    const backend = new UltraHonkBackend(program.bytecode, bb);
    const vk = await backend.getVerificationKey({ verifierTarget: 'evm' });
    await writeFile(join(targetDir, 'eligibility.vk'), vk);
    const solidity = await backend.getSolidityVerifier(vk, { verifierTarget: 'evm' });
    await mkdir(dirname(verifierOut), { recursive: true });
    const header = '// SPDX-License-Identifier: Apache-2.0\n// AUTO-GENERATED by packages/circuits/scripts/build.mjs from the eligibility circuit. Do not edit.\n';
    await writeFile(verifierOut, header + solidity.replace(/^\/\/ SPDX-License-Identifier:.*\n/m, ''));
    console.log(`  verifier generated        HonkVerifier.sol (${(solidity.length / 1024).toFixed(0)} KB)`);
  } finally {
    await bb.destroy();
  }
  console.log(`  circuit build finished in ${((Date.now() - started) / 1000).toFixed(1)}s`);
}

main().catch((err) => {
  console.error(err?.diagnostics ?? err);
  process.exit(1);
});
